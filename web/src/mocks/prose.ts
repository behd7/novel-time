export function proseFor(mood: Mood, seq: number): string {
  const paragraphs = PARAGRAPHS[mood];
  const window = 8;
  const start = ((seq - 1) * 3) % (paragraphs.length - window + 1);
  return paragraphs.slice(start, start + window).join('\n\n');
}

