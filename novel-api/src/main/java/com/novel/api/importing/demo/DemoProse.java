    static String title(DemoNovel.DemoMood mood, int bookIndex, int seq) {
        List<String> titles = CHAPTER_TITLES.get(mood);
        return titles.get(Math.floorMod(bookIndex * 7 + seq - 1, titles.size()));
    }

    static String body(DemoNovel.DemoMood mood, int bookIndex, int seq) {
        List<String> paragraphs = PARAGRAPHS.get(mood);
        int maxStart = paragraphs.size() - PARAGRAPHS_PER_CHAPTER;
        int start = Math.floorMod(bookIndex * 5 + seq * 3, maxStart + 1);
        return String.join("\n\n",
                paragraphs.subList(start, start + PARAGRAPHS_PER_CHAPTER));
    }
