-- ============================================================================
-- 搜索索引同步用的版本号
--
-- 为什么不用 updated_at：DATETIME 只有秒级精度，同一秒内的两次更新会得到相同的版本，
-- 消费端拿"外部版本号"丢弃旧消息时就会误丢真正的更新。
--
-- 为什么版本号可靠：UPDATE 会持有行锁，版本自增天然被串行化，
-- 所以"谁后提交谁版本大"，旧消息一定比新消息版本小，可以安全丢弃。
--
-- 注意：它不参与 MyBatis-Plus 的乐观锁（实体上不加 @Version），
-- 只是一个给搜索引擎用的单调递增序号，别把两种语义混在一起。
-- ============================================================================
ALTER TABLE novel
    ADD COLUMN version BIGINT UNSIGNED NOT NULL DEFAULT 0 COMMENT '搜索索引同步版本号，内容每变更一次 +1';
