package com.novel.core.event;

/**
 * 业务事件的发布出口。
 *
 * <p>这是全项目唯一的"把变更告诉外面"的口子。约定只有一条，但必须守住：
 * <b>实现必须与业务写入在同一个事务里落库，绝不允许直接发 MQ</b>。
 *
 * <p>为什么这么苛刻：事务还没提交就把消息发出去，broker 可能先于数据库把消息投给消费者，
 * 消费者回查时看到的还是旧数据；反过来数据库提交了而消息没发出去，索引就永久缺一条。
 * 两种失败都没有"事后发现"的办法。先落一条待投递记录、提交后再由后台任务发，
 * 才能保证"库里既然有这次变更，事件就一定不会丢"。
 *
 * <p>端口故意只提供"某本书变了"这一种粗粒度语义：调用方不需要知道消息里该带什么字段，
 * 实现负责取版本号、拼消息、写 Outbox。
 */
public interface NovelEventPublisher {

    /**
     * 声明"这本书变了"。必须在写业务数据的事务内调用。
     *
     * @param novelId 小说 id
     * @param type    变更类型
     */
    void novelChanged(long novelId, NovelChangeType type);
}
